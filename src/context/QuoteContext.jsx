import { createContext, useContext, useEffect, useReducer } from 'react'
import { z } from 'zod'
import { Quote } from '../lib/schema'
import { makeId } from '../lib/id'
import { loadJSON, saveJSON, KEYS } from '../lib/storage'

// Reducer-level guardrail: Quote's zod schema (src/lib/schema.js) requires
// qty > 0, rate >= 0 (or null), and 0 <= taxRate <= 1. zod rejects the
// WHOLE saved object if any one field is out of range, so an out-of-bound
// value reaching here would silently wipe the entire quote on the next
// reload (loadJSON falls back to emptyQuote()), not just reset that field.
// The UI inputs (Sheet.jsx, SheetLineItem.jsx) already clamp at the source,
// but this is the single choke point every dispatch goes through, so it's
// the safer place to guarantee it, including for model-extracted items.
function clampLineItem(item) {
  const qty = Number(item.qty)
  const rate = item.rate == null ? null : Number(item.rate)
  return {
    ...item,
    // LineItem.description requires min length 1 too - EditableText lets
    // a user clear a description to '', which is the same failure class.
    description: item.description && item.description.trim() ? item.description : 'New line',
    qty: Number.isFinite(qty) && qty > 0 ? qty : 1,
    rate: rate != null && Number.isFinite(rate) && rate >= 0 ? rate : null,
  }
}

function clampTaxRate(taxRate) {
  const num = Number(taxRate)
  return Number.isFinite(num) ? Math.min(1, Math.max(0, num)) : 0
}

function nextQNumber(quotes) {
  return `Q-${String(quotes.length + 1).padStart(3, '0')}`
}

function emptyQuote(qNumber = 'Q-001') {
  return {
    id: makeId('q'),
    createdAt: Date.now(),
    qNumber,
    client: { name: '', detail: '' },
    items: [],
    notes: '',
    taxRate: 0,
    currency: 'USD',
  }
}

// One quote's worth of edits (items, client, tax). Operates on a single
// Quote object - the outer reducer below maps this over whichever quote
// in the list is currently active.
function quoteReducer(state, action) {
  switch (action.type) {
    case 'ITEM_ADDED': {
      const item = clampLineItem({
        id: makeId('li'),
        description: action.description ?? 'New line',
        qty: action.qty ?? 1,
        unit: action.unit ?? 'item',
        rate: action.rate ?? null,
        source: action.source ?? 'user',
      })
      return { ...state, items: [...state.items, item] }
    }

    case 'ITEM_EDITED': {
      return {
        ...state,
        items: state.items.map((item) =>
          item.id === action.id ? clampLineItem({ ...item, ...action.patch }) : item
        ),
      }
    }

    case 'ITEM_REMOVED':
      return { ...state, items: state.items.filter((item) => item.id !== action.id) }

    case 'ITEM_CONFIRMED':
      return {
        ...state,
        items: state.items.map((item) =>
          item.id === action.id ? { ...item, source: 'user' } : item
        ),
      }

    case 'CLIENT_SET':
      return { ...state, client: { ...state.client, ...action.client } }

    case 'TAX_SET':
      return { ...state, taxRate: clampTaxRate(action.taxRate) }

    default:
      return state
  }
}

// Top-level state: every saved quote, plus which one is open. See
// docs/UI.md's Dashboard section for the view this backs.
function topReducer(state, action) {
  switch (action.type) {
    case 'QUOTES_LOADED':
      return action.state

    case 'QUOTE_CREATED':
      // The id is generated by the caller (not here) so a component can
      // navigate to /quote/:id in the same handler that dispatches this -
      // see Dashboard.jsx's "New quote" button.
      return { quotes: [...state.quotes, action.quote], activeId: action.quote.id }

    case 'QUOTE_SELECTED':
      return state.quotes.some((q) => q.id === action.id) ? { ...state, activeId: action.id } : state

    case 'QUOTE_DELETED': {
      const quotes = state.quotes.filter((q) => q.id !== action.id)
      const activeId = state.activeId === action.id ? null : state.activeId
      return { quotes, activeId }
    }

    default:
      return {
        ...state,
        quotes: state.quotes.map((q) =>
          q.id === state.activeId ? quoteReducer(q, action) : q
        ),
      }
  }
}

const StoredState = z.object({
  quotes: z.array(Quote),
  activeId: z.string().nullable(),
})

function loadInitialState() {
  const stored = loadJSON(KEYS.quotes, StoredState, null)
  if (stored) return stored

  // Migrate a pre-dashboard single quote (hushquote.activeQuote.v1) into
  // the new list, once. Harmless no-op for anyone who never had one.
  const legacy = loadJSON(KEYS.quote, Quote, null)
  if (legacy && (legacy.items.length > 0 || legacy.client?.name)) {
    return { quotes: [legacy], activeId: legacy.id }
  }
  return { quotes: [], activeId: null }
}

const QuoteListStateContext = createContext(null)
const QuoteDispatchContext = createContext(null)

export function QuoteProvider({ children }) {
  const [state, dispatch] = useReducer(topReducer, undefined, loadInitialState)

  useEffect(() => {
    saveJSON(KEYS.quotes, state)
  }, [state])

  return (
    <QuoteListStateContext.Provider value={state}>
      <QuoteDispatchContext.Provider value={dispatch}>
        {children}
      </QuoteDispatchContext.Provider>
    </QuoteListStateContext.Provider>
  )
}

// All saved quotes, for the Dashboard's list + stats.
export function useQuoteList() {
  const ctx = useContext(QuoteListStateContext)
  if (!ctx) throw new Error('useQuoteList must be used inside QuoteProvider')
  return ctx.quotes
}

// The currently-open quote (Workspace and everything under it). Falls
// back to a throwaway empty quote if nothing is active yet, so existing
// consumers (Sheet, MarginRail, TopBar...) never need a null check.
export function useQuote() {
  const ctx = useContext(QuoteListStateContext)
  if (!ctx) throw new Error('useQuote must be used inside QuoteProvider')
  return ctx.quotes.find((q) => q.id === ctx.activeId) ?? emptyQuote()
}

export function useQuoteDispatch() {
  const ctx = useContext(QuoteDispatchContext)
  if (!ctx) throw new Error('useQuoteDispatch must be used inside QuoteProvider')
  return ctx
}

export { emptyQuote, nextQNumber }
